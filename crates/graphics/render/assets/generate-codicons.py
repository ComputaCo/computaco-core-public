def render(font_path, cp, size):
    font = ImageFont.truetype(font_path, size)
    mask = Image.new("L", (size, size), 0)
    ImageDraw.Draw(mask).text((0, 0), chr(cp), font=font, fill=255)
    out = Image.new("LA", (size, size), (255, 0))
    out.putalpha(mask)
    return out


def main():
    font_path = sys.argv[1]
    OUT.mkdir(parents=True, exist_ok=True)
    rows = []
    for name, (cp, sizes) in sorted(GLYPHS.items()):
        for size in sizes:
            img = render(font_path, cp, size)
            if img.getchannel("A").getbbox() is None:
                raise SystemExit(f"{name} (U+{cp:04X}) is empty in {font_path}")
            file = f"codicon-{name}-{size}.png"
            img.save(OUT / file, optimize=True)
            rows.append((f"symbol/codicon-{name}-{size}", f"icons/vscode/{file}"))
    lines = ["// Generated by assets/generate-codicons.py; do not edit.",
             "pub const CODICONS: &[(&str, &str)] = &["]
    lines += [f'    ("{a}", "{f}"),' for a, f in rows]
    lines.append("];")
    TABLE.write_text("\n".join(lines) + "\n")
    print(f"{len(rows)} masks")


if __name__ == "__main__":
    main()
