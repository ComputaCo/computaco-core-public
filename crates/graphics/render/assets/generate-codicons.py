"""Pre-render the Visual Studio Code codicons the simulated VS Code draws (requires pillow).

    generate-codicons.py /usr/share/code/resources/app/out/media/codicon.ttf

Each glyph is rasterised by FreeType at the pixel size VS Code sets it in (16 px in tool
bars and lists, 24 px in the activity bar), into an em-square alpha mask the renderer
tints (`Primitive::Symbol`), so the simulator draws the page's own icons at 1:1. The font
is VS Code 1.143's (@vscode/codicons 0.0.46), CC-BY-4.0 for the icons and MIT for the
code (icons/vscode/LICENSE.txt). Also writes src/codicons.rs, the embedded lookup table.
"""
