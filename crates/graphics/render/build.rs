//! Pins every file the renderer draws with and nothing else reads (`src/render_pack.rs`):
//! DejaVu, the icons and wallpapers of the platforms this build draws, the symbol
//! masks, and the applications' own icons (assets/apps). Each is listed with its SHA-256 and size; a build without `lazy-render`
//! embeds the bytes, a build with it fetches them the first time a frame needs one.
use sha2::{Digest, Sha256};
use std::fmt::Write;
use std::path::Path;

const DEJAVU: [&str; 5] = [
    "dejavu-mono.ttf",
    "dejavu-sans.ttf",
    "dejavu-sans-bold.ttf",
    "dejavu-sans-oblique.ttf",
    "dejavu-sans-bold-oblique.ttf",
];
const PLATFORMS: [&str; 5] = ["macos", "windows", "ubuntu", "ios", "android"];

fn main() {
    let assets = Path::new(env!("CARGO_MANIFEST_DIR")).join("assets");
    let lazy = std::env::var_os("CARGO_FEATURE_LAZY_RENDER").is_some();
    let drawn: Vec<&str> = PLATFORMS
        .into_iter()
        .filter(|p| std::env::var_os(format!("CARGO_FEATURE_OS_{}", p.to_uppercase())).is_some())
        .collect();
    let mut files: Vec<String> = DEJAVU.iter().map(|f| format!("fonts/{f}")).collect();
    for platform in &drawn {
        files.push(format!("wallpapers/{platform}.jpg"));
    }
    let listed = |dir: &str| -> Vec<String> {
        let mut names: Vec<String> = std::fs::read_dir(assets.join(dir))
            .unwrap_or_else(|e| panic!("assets/{dir}: {e}"))
            .map(|e| e.unwrap().file_name().into_string().unwrap())
            .filter(|n| n.ends_with(".png"))
            .collect();
        names.sort();
        names
    };
    for name in listed("icons") {
        if drawn.iter().any(|p| name.starts_with(&format!("{p}-"))) {
            files.push(format!("icons/{name}"));
        }
    }
    for name in listed("symbols") {
        files.push(format!("symbols/{name}"));
    }
    // VS Code's codicons, which its simulated workbench draws with.
    for name in listed("icons/vscode") {
        files.push(format!("icons/vscode/{name}"));
    }
    // Applications' own artwork (FreeCAD's icons), drawn whatever the platform.
    let mut apps: Vec<String> = std::fs::read_dir(assets.join("apps"))
        .map(|d| {
            d.map(|e| e.unwrap().file_name().into_string().unwrap())
                .collect()
        })
        .unwrap_or_default();
    apps.sort();
    for app in apps {
        for name in listed(&format!("apps/{app}")) {
            files.push(format!("apps/{app}/{name}"));
        }
    }
    // KiCad 7's bitmaps, which the simulated KiCad draws its tool bars and launcher with.
    for name in listed("icons/kicad") {
        files.push(format!("icons/kicad/{name}"));
    }
    files.sort();
    // A static, not a constant: a constant's bytes are copied into every place that uses it.
    let mut out = String::from(
        "/// Generated by build.rs: every file the renderer draws with, sorted by path.\n",
    );
    writeln!(out, "const RENDER_FILE_COUNT: usize = {};", files.len()).unwrap();
    writeln!(
        out,
        "pub static RENDER_FILES: [RenderFile; RENDER_FILE_COUNT] = ["
    )
    .unwrap();
    for file in &files {
        let path = assets.join(file);
        println!("cargo:rerun-if-changed={}", path.display());
        let bytes = std::fs::read(&path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
        let sha256 = format!("{:x}", Sha256::digest(&bytes));
        let embedded = if lazy {
            "None".to_owned()
        } else {
            format!("Some(include_bytes!({:?}))", path.display().to_string())
        };
        writeln!(
            out,
            "    RenderFile {{ file: {file:?}, sha256: {sha256:?}, bytes: {}, embedded: {embedded} }},",
            bytes.len()
        )
        .unwrap();
    }
    out.push_str("];\n");
    println!("cargo:rerun-if-changed=assets/icons");
    println!("cargo:rerun-if-changed=assets/symbols");
    println!("cargo:rerun-if-changed=assets/icons/vscode");
    println!("cargo:rerun-if-changed=assets/apps");
    println!("cargo:rerun-if-changed=assets/icons/kicad");
    let dest = Path::new(&std::env::var("OUT_DIR").unwrap()).join("render_files.rs");
    std::fs::write(dest, out).unwrap();
}
