//! GIMP 2.10.36's menu bar as the real application exposes it (read from its accessibility tree
//! on the reference machine, fidelity/targets/gimp.json): each menu's items, separators and submenus, in order.
//! Entries the simulated GIMP does not implement are listed too, insensitive, as a menu lists
//! what it cannot do now; the ones it does are bound to commands in `gimp::bindings`.
//! Names are the ones the application shows without their accelerators; names that carry state
//! (Undo's step, the image in the Windows menu, the Overwrite file) are the generic ones.

